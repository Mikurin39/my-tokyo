"""Build js/spots.js (ranking + spot details) from data/spots/*.json and data/spots/genres.json.

  python3 tools/build_spots.py

data/spots/<group>.json : arrays of spot fact sheets (see keys below).
data/spots/genres.json  : [{"key","label","note","ids":[...]}] in tab order.
data/spots/images.json  : {"<id>": {"img": "img/...jpg", "credit": {...}}}  photo + credit per spot.
"""
import json, glob, os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
D = os.path.join(ROOT, "data", "spots")
KEEP = ["name","name_ja","area","about","address","lat","lng","phone","hours","closed","price","station","walk_min",
        "parking","car","website","instagram","tags","meal","duration_min","reviews"]
spots = {}
for f in sorted(glob.glob(os.path.join(D, "*.json"))):
    if os.path.basename(f) in ("genres.json", "images.json"): continue
    for s in json.load(open(f, encoding="utf-8")):
        spots[s["id"]] = {k: s.get(k) for k in KEEP if s.get(k) not in (None, "", [])}
images = json.load(open(os.path.join(D, "images.json"), encoding="utf-8"))
for i, v in images.items():
    if i in spots: spots[i].update(v)
genres = json.load(open(os.path.join(D, "genres.json"), encoding="utf-8"))
bad = [(g["key"], i) for g in genres for i in g["ids"] if i not in spots]
if bad: sys.exit(f"unknown ids: {bad}")
used = {i for g in genres for i in g["ids"]}
spots = {k: v for k, v in spots.items() if k in used}
out = {"checked": "November 2026", "genres": genres, "spots": spots}
open(os.path.join(ROOT, "js", "spots.js"), "w", encoding="utf-8").write(
    "/* Generated by tools/build_spots.py from data/spots/. Edit the JSON there, not this file. */\nwindow.SPOTS = "
    + json.dumps(out, ensure_ascii=False, indent=0) + ";\n")
print(len(spots), "spots;", [(g["key"], len(g["ids"])) for g in genres])
print("no photo:", [k for k, v in spots.items() if "img" not in v])
